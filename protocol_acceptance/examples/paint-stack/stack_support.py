def paths(crate):
    base = ROOT / crate
    if crate == "paint-app":
        return base / "acceptance-specification.toml", base / "acceptance-package.toml", base / "acceptance-decision.toml"
    base = base / "acceptance" / SPEC_IDS[crate]
    return base / "acceptance-specification.toml", base / "acceptance.toml", base / "acceptance-decision.toml"


def load(path):
    return tomllib.loads(path.read_text())


def scalar(value):
    if isinstance(value, dict):
        return "{ " + ", ".join(json.dumps(k) + " = " + scalar(v) for k, v in value.items()) + " }"
    if isinstance(value, list):
        return "[" + ", ".join(scalar(v) for v in value) + "]"
    return json.dumps(value, ensure_ascii=False)


def dumps(doc):
    """Readable top-level tables; nested identities remain inline TOML tables."""
    lines = []
    for key, value in doc.items():
        if isinstance(value, dict):
            lines += [f"[{key}]"] + [f"{k} = {scalar(v)}" for k, v in value.items()] + [""]
        elif isinstance(value, list) and value and isinstance(value[0], dict):
            for row in value:
                lines += [f"[[{key}]]"] + [f"{k} = {scalar(v)}" for k, v in row.items()] + [""]
        else:
            raise ValueError(f"unexpected top-level field: {key}")
    text = "\n".join(lines)
    assert tomllib.loads(text) == doc
    return text


def save(path, doc):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("# GENERATED by gen_stack.py from real runs; do not hand-edit.\n" + dumps(doc))
